-- 多平台 AI 模型管理：API Key 用 AES-GCM-256 加密后存库（主密钥不进库、不进代码）
CREATE TABLE ai_provider (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    provider        VARCHAR(64)  NOT NULL,
    name            VARCHAR(128) NOT NULL,
    base_url        VARCHAR(255) NOT NULL,
    model           VARCHAR(128) NOT NULL,
    encrypted_key   BYTEA        NOT NULL,
    iv              BYTEA        NOT NULL,
    gcm_tag         BYTEA        NOT NULL,
    encrypt_algo    VARCHAR(32)  NOT NULL DEFAULT 'aes-gcm-256',
    priority        INT          NOT NULL DEFAULT 100,
    status          SMALLINT     NOT NULL DEFAULT 1,
    timeout_seconds INT          NOT NULL DEFAULT 60,
    last_status     VARCHAR(16)  NULL,
    last_error      VARCHAR(500) NULL,
    last_checked_at TIMESTAMP(3) NULL,
    last_latency_ms BIGINT       NULL,
    success_count   INT          NOT NULL DEFAULT 0,
    failure_count   INT          NOT NULL DEFAULT 0,
    created_at      TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at      TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_ai_provider_priority ON ai_provider (status, priority);
