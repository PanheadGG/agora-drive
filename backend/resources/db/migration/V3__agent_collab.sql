-- 网盘数据要素悬赏协同（Agent 匹配 Demo）
-- 角色约定：0=普通个人用户，1=管理员（已有），2=企业需求用户（本次新增）

CREATE TABLE data_bounty (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    publisher_user_id BIGINT       NOT NULL,
    title             VARCHAR(255) NOT NULL,
    raw_desc          TEXT         NOT NULL,
    structured_json   JSONB        NOT NULL,
    status            SMALLINT     NOT NULL DEFAULT 1,
    created_at        TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at        TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_data_bounty_publisher ON data_bounty (publisher_user_id);
CREATE INDEX idx_data_bounty_status ON data_bounty (status);

CREATE TABLE agent_scan_task (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    bounty_id           BIGINT       NOT NULL,
    user_id             BIGINT       NOT NULL,
    auth_scope_json     JSONB        NOT NULL,
    task_status         SMALLINT     NOT NULL DEFAULT 0,
    total_file_count    INT          NOT NULL DEFAULT 0,
    success_parse_count INT          NOT NULL DEFAULT 0,
    fail_parse_count    INT          NOT NULL DEFAULT 0,
    created_at          TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    finished_at         TIMESTAMP(3) NULL
);
CREATE INDEX idx_agent_scan_task_bounty ON agent_scan_task (bounty_id);
CREATE INDEX idx_agent_scan_task_user ON agent_scan_task (user_id);

CREATE TABLE agent_scan_result (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    scan_task_id   BIGINT       NOT NULL,
    user_file_id   BIGINT       NOT NULL,
    match_level    SMALLINT     NOT NULL,
    parse_status   SMALLINT     NOT NULL DEFAULT 0,
    parse_method   VARCHAR(64)  NULL,
    parsed_summary TEXT         NULL,
    evidence_text  TEXT         NULL,
    risk_tag       VARCHAR(128) NULL,
    risk_desc      TEXT         NULL,
    user_review    SMALLINT     NOT NULL DEFAULT 0,
    review_note    TEXT         NULL,
    created_at     TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_agent_scan_result_task ON agent_scan_result (scan_task_id);
CREATE INDEX idx_agent_scan_result_file ON agent_scan_result (user_file_id);
