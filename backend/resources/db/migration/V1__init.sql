-- 网盘基础表结构（对齐 docs/数据库设计.md，按 PostgreSQL 方言落地）
CREATE TABLE "user" (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username    VARCHAR(64)  NOT NULL,
    password    VARCHAR(128) NOT NULL,
    total_quota BIGINT       NOT NULL DEFAULT 10737418240,
    used_size   BIGINT       NOT NULL DEFAULT 0,
    status      SMALLINT     NOT NULL DEFAULT 1,
    created_at  TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at  TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE UNIQUE INDEX uk_user_username ON "user" (username);

CREATE TABLE file_meta (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sha256     VARCHAR(64)  NOT NULL,
    total_size BIGINT       NOT NULL,
    created_at TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE UNIQUE INDEX uk_file_meta_sha256 ON file_meta (sha256);

CREATE TABLE user_file (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT       NOT NULL,
    parent_id  BIGINT       NULL,
    meta_id    BIGINT       NULL,
    file_name  VARCHAR(255) NOT NULL,
    is_folder  SMALLINT     NOT NULL DEFAULT 0,
    is_recycle SMALLINT     NOT NULL DEFAULT 0,
    created_at TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_user_file_dir ON user_file (user_id, parent_id, is_recycle);
CREATE INDEX idx_user_file_meta ON user_file (meta_id);
CREATE UNIQUE INDEX uk_user_file_root_name ON user_file (user_id, file_name)
    WHERE parent_id IS NULL AND is_recycle = 0;
CREATE UNIQUE INDEX uk_user_file_name ON user_file (user_id, parent_id, file_name)
    WHERE parent_id IS NOT NULL AND is_recycle = 0;

CREATE TABLE upload_task (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id        BIGINT       NOT NULL,
    task_id        VARCHAR(64)  NOT NULL,
    file_name      VARCHAR(255) NOT NULL,
    total_size     BIGINT       NOT NULL,
    total_chunk    INT          NOT NULL,
    sha256         VARCHAR(64)  NULL,
    finished_chunk INT          NOT NULL DEFAULT 0,
    status         SMALLINT     NOT NULL DEFAULT 0,
    expire_at      TIMESTAMP(3) NOT NULL,
    created_at     TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at     TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE UNIQUE INDEX uk_upload_task_task_id ON upload_task (task_id);
CREATE INDEX idx_upload_task_expire ON upload_task (expire_at);
CREATE INDEX idx_upload_task_user ON upload_task (user_id);
