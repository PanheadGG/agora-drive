-- 协同改为「协同号 + 协同密码」方式，支持多成员、产品动态增大
ALTER TABLE collab_session ADD COLUMN collab_code VARCHAR(16) NULL;
ALTER TABLE collab_session ADD COLUMN collab_password_hash VARCHAR(128) NULL;
ALTER TABLE collab_session ADD COLUMN description TEXT NOT NULL DEFAULT '';
ALTER TABLE collab_session ADD COLUMN owner_id BIGINT NULL;
CREATE UNIQUE INDEX uk_collab_code ON collab_session (collab_code) WHERE collab_code IS NOT NULL;

-- 协同成员：发起人 + 通过协同号加入的其他人
CREATE TABLE collab_member (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id   BIGINT       NOT NULL,
    user_id      BIGINT       NOT NULL,
    role         SMALLINT     NOT NULL DEFAULT 1,
    scope_json   JSONB        NOT NULL DEFAULT '[]'::jsonb,
    file_count   INT          NOT NULL DEFAULT 0,
    rows_contributed INT      NOT NULL DEFAULT 0,
    groups_contributed INT    NOT NULL DEFAULT 0,
    status       SMALLINT     NOT NULL DEFAULT 0,
    joined_at    TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE UNIQUE INDEX uk_collab_member ON collab_member (session_id, user_id);
CREATE INDEX idx_collab_member_user ON collab_member (user_id);

-- 历史数据补齐：旧协同会话的发起人作为 owner
UPDATE collab_session SET owner_id = initiator_id WHERE owner_id IS NULL;
