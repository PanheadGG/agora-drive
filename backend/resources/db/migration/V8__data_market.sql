-- 数据卖方 Agent + 数据交易市场
-- 核心：Agent 在卖方网盘内把 Raw Data 加工成"数据产品"，市场只见产品描述，不见原始内容。

-- Agent 身份：每个用户一个逻辑 Agent（单进程多租户模拟，P3 可拆成独立服务）
CREATE TABLE agent_peer (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id      BIGINT       NOT NULL,
    agent_name   VARCHAR(64)  NOT NULL,
    status       SMALLINT     NOT NULL DEFAULT 1,
    last_seen_at TIMESTAMP(3) NULL,
    created_at   TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE UNIQUE INDEX uk_agent_peer_user ON agent_peer (user_id);

-- 数据产品：Agent 的产出物
CREATE TABLE data_product (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_id        BIGINT       NOT NULL,
    title           VARCHAR(255) NOT NULL,
    template_key    VARCHAR(64)  NOT NULL,
    template_label  VARCHAR(128) NOT NULL,
    schema_json     JSONB        NOT NULL DEFAULT '[]'::jsonb,
    row_count       BIGINT       NOT NULL DEFAULT 0,
    contributing_files INT       NOT NULL DEFAULT 0,
    coverage_start  VARCHAR(32)  NULL,
    coverage_end    VARCHAR(32)  NULL,
    quality_json    JSONB        NOT NULL DEFAULT '{}'::jsonb,
    tags_json       JSONB        NOT NULL DEFAULT '[]'::jsonb,
    sample_json     JSONB        NOT NULL DEFAULT '[]'::jsonb,
    build_receipt   JSONB        NOT NULL DEFAULT '{}'::jsonb,
    pii_status      VARCHAR(32)  NOT NULL DEFAULT 'clean',
    status          SMALLINT     NOT NULL DEFAULT 0,
    source_kind     VARCHAR(16)  NOT NULL DEFAULT 'solo',
    ai_enabled      SMALLINT     NOT NULL DEFAULT 0,
    created_at      TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at      TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_data_product_owner ON data_product (owner_id);
CREATE INDEX idx_data_product_status ON data_product (status);

-- 产品构建流水（复用原扫描任务的执行框架）
CREATE TABLE product_build_task (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id  BIGINT       NOT NULL,
    user_id     BIGINT       NOT NULL,
    scope_json  JSONB        NOT NULL DEFAULT '[]'::jsonb,
    task_status SMALLINT     NOT NULL DEFAULT 0,
    total_file_count INT    NOT NULL DEFAULT 0,
    success_parse_count INT NOT NULL DEFAULT 0,
    fail_parse_count INT    NOT NULL DEFAULT 0,
    ai_enabled  SMALLINT     NOT NULL DEFAULT 0,
    model_name  VARCHAR(64)  NULL,
    created_at  TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    finished_at TIMESTAMP(3) NULL
);
CREATE INDEX idx_product_build_task_product ON product_build_task (product_id);

-- 构建用料：原料溯源（可复现凭证）
CREATE TABLE product_build_item (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    task_id      BIGINT       NOT NULL,
    user_file_id BIGINT       NOT NULL,
    file_sha256  VARCHAR(64)  NULL,
    file_name    VARCHAR(255) NULL,
    parse_method VARCHAR(64)  NULL,
    rows_contributed INT      NOT NULL DEFAULT 0,
    status       SMALLINT     NOT NULL DEFAULT 0,
    risk_tag     VARCHAR(64)  NULL,
    note         VARCHAR(512) NULL,
    created_at   TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_product_build_item_task ON product_build_item (task_id);

-- 上架记录
CREATE TABLE product_listing (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id   BIGINT       NOT NULL,
    seller_id    BIGINT       NOT NULL,
    title        VARCHAR(255) NOT NULL,
    summary      TEXT         NOT NULL DEFAULT '',
    field_list   JSONB        NOT NULL DEFAULT '[]'::jsonb,
    tags_json    JSONB        NOT NULL DEFAULT '[]'::jsonb,
    domain       VARCHAR(64)  NOT NULL,
    coverage_start VARCHAR(32) NULL,
    coverage_end VARCHAR(32)  NULL,
    row_count    BIGINT       NOT NULL DEFAULT 0,
    quality_score INT         NOT NULL DEFAULT 0,
    price_cents  BIGINT       NOT NULL DEFAULT 0,
    license_type VARCHAR(32)  NOT NULL DEFAULT 'internal',
    status       SMALLINT     NOT NULL DEFAULT 1,
    listed_at    TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    delisted_at  TIMESTAMP(3) NULL
);
CREATE INDEX idx_product_listing_status ON product_listing (status, domain);
CREATE INDEX idx_product_listing_seller ON product_listing (seller_id);

-- 买方采购需求（由悬赏语义迁移而来）
CREATE TABLE market_demand (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    buyer_id      BIGINT       NOT NULL,
    title         VARCHAR(255) NOT NULL,
    raw_desc      TEXT         NOT NULL,
    structured_json JSONB      NOT NULL DEFAULT '{}'::jsonb,
    budget_cents  BIGINT       NOT NULL DEFAULT 0,
    status        SMALLINT     NOT NULL DEFAULT 1,
    created_at    TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at    TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_market_demand_buyer ON market_demand (buyer_id);

-- 匹配与推送
CREATE TABLE market_match (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    demand_id   BIGINT       NOT NULL,
    listing_id  BIGINT       NOT NULL,
    score       INT          NOT NULL DEFAULT 0,
    reasons_json JSONB       NOT NULL DEFAULT '[]'::jsonb,
    state       SMALLINT     NOT NULL DEFAULT 0,
    pushed_at   TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    read_at     TIMESTAMP(3) NULL,
    note        VARCHAR(512) NULL
);
CREATE UNIQUE INDEX uk_market_match_pair ON market_match (demand_id, listing_id);
CREATE INDEX idx_market_match_demand ON market_match (demand_id, state);

-- Agent 协同会话：联合产品
CREATE TABLE collab_session (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    template_key   VARCHAR(64)  NOT NULL,
    template_label VARCHAR(128) NOT NULL,
    title          VARCHAR(255) NOT NULL,
    initiator_id   BIGINT       NOT NULL,
    partner_id     BIGINT       NOT NULL,
    state          SMALLINT     NOT NULL DEFAULT 0,
    k_threshold    INT          NOT NULL DEFAULT 5,
    product_id     BIGINT       NULL,
    message        VARCHAR(512) NULL,
    created_at     TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at     TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_collab_session_initiator ON collab_session (initiator_id);
CREATE INDEX idx_collab_session_partner ON collab_session (partner_id);

-- 协同各方贡献（只存聚合后的分组统计，不含原始行）
CREATE TABLE collab_contribution (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id    BIGINT       NOT NULL,
    user_id       BIGINT       NOT NULL,
    aggregate_json JSONB      NOT NULL DEFAULT '[]'::jsonb,
    group_count   INT          NOT NULL DEFAULT 0,
    suppressed_groups INT      NOT NULL DEFAULT 0,
    approved      SMALLINT     NOT NULL DEFAULT 0,
    created_at    TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE UNIQUE INDEX uk_collab_contribution ON collab_contribution (session_id, user_id);

-- 交付申请（Demo 最小化：申请 → 同意 → 标记已交付）
CREATE TABLE delivery_request (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    match_id   BIGINT       NOT NULL,
    buyer_id   BIGINT       NOT NULL,
    seller_id  BIGINT       NOT NULL,
    status     SMALLINT     NOT NULL DEFAULT 0,
    note       VARCHAR(512) NULL,
    created_at TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_delivery_request_buyer ON delivery_request (buyer_id);
CREATE INDEX idx_delivery_request_seller ON delivery_request (seller_id);

